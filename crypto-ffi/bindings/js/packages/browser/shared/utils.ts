import { logLevel, type PlatformHelpers } from "../../../shared/shared/utils";
import { type Database, DatabaseKey } from "@wireapp/core-crypto/browser";
import { serve } from "bun";

import { Browser, Page, launch } from "puppeteer";

let server: ReturnType<typeof serve>;
let browser: Browser;
let page: Page;

export function setPage(p: Page) {
    page = p;
}

export function getPage(): Page {
    if (!page) {
        throw new Error("Page not initialized");
    }
    return page;
}

// we require mocha rootHooks for browser
export async function sharedSetup() {}
export async function sharedTeardown() {}

/**
 * Log entry from the core crypto logger
 */
export interface LogEntry {
    level: number;
    message: string;
    context: string;
}

export async function setPlatformHelpers() {
    return await getPage().evaluate(() => {
        class PlatformHelpersImpl implements PlatformHelpers {
            async newDatabase(
                location?: string,
                key?: DatabaseKey
            ): Promise<Database> {
                const finalKey = key ?? helpers.newDatabaseKey();
                const finalLocation = location ?? crypto.randomUUID();
                return ccModule.Database.open(finalLocation, finalKey);
            }
        }
        globalThis.platformHelpers = new PlatformHelpersImpl();
    });
}

type ExecuteScript = Parameters<typeof page.evaluate>[0];

export async function runOnPlatform<Args extends unknown[], T>(
    script: (...args: Args) => T,
    ...args: Args
): Promise<T> {
    return getPage().evaluate(script as ExecuteScript, ...args) as Promise<T>;
}

export async function setupBrowser(protocolTimeout?: number) {
    server = serve({
        port: 3000,
        async fetch(req) {
            const url = new URL(req.url);

            if (url.pathname === "/") {
                return new Response("<!doctype html>", {
                    headers: { "Content-Type": "text/html" },
                });
            }

            if (url.pathname === "/favicon.ico") {
                return new Response(null, { status: 204 });
            }

            const roots = ["./packages/core-crypto/dist/browser", "."];

            for (const root of roots) {
                const file = Bun.file(`${root}${url.pathname}`);
                if (await file.exists()) {
                    return new Response(file);
                }
            }

            return new Response("Not found", { status: 404 });
        },
    });
    browser = await launch({
        headless: "shell",
        protocolTimeout,
    });

    const page = await browser.newPage();
    setPage(page);

    page.on("console", (msg) => {
        if (logLevel >= 1) {
            console.log(`[browser:${msg.type()}]`, msg.text());
        }
    });

    await page.goto(server.url.toString());

    await page.evaluate(async () => {
        // @ts-expect-error runtime browser import
        globalThis.ccModule = await import("/corecrypto.js");

        await globalThis.ccModule.initWasmModule(
            "/autogenerated/wasm-bindgen/index_bg.wasm"
        );
    });
}

export async function teardownBrowser() {
    await browser.close();
    await server.stop();
}
