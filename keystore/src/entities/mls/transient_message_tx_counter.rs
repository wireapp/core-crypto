use const_format::formatcp;

use crate::{
    CryptoKeystoreResult,
    entities::helpers::{count_helper, delete_helper, get_helper, get_helper_composite_key, load_all_helper},
    traits::{BorrowPrimaryKey, EntityDatabaseMutation, EntityDeleteBorrowed, EntityGetBorrowed, PrimaryKey},
};

#[derive(core_crypto_macros::Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct TransientMessageTxCounter {
    pub conversation_id: Vec<u8>,
    pub count: u32,
}

#[derive(Clone, Debug, Hash, PartialEq, Eq, derive_more::Constructor)]
pub struct TransientMessageTxCounterPk {
    conversation_id: Vec<u8>,
}

impl TransientMessageTxCounter {
    const TABLE_NAME: &str = "transient_message_tx_counters";
    const PRIMARY_KEY_COLUMN_NAME: &str = "conversation_id";

    fn from_row(row: &rusqlite::Row<'_>) -> rusqlite::Result<Self> {
        Ok(Self {
            conversation_id: row.get("conversation_id")?,
            count: row.get("count")?,
        })
    }
}

impl PrimaryKey for TransientMessageTxCounter {
    type PrimaryKey = TransientMessageTxCounterPk;
    fn primary_key(&self) -> Self::PrimaryKey {
        TransientMessageTxCounterPk::new(self.conversation_id.clone())
    }
}

impl crate::traits::Entity for TransientMessageTxCounter {
    const TABLE_NAME: &str = Self::TABLE_NAME;

    fn get(
        conn: &rusqlite::Connection,
        key: &TransientMessageTxCounterPk,
    ) -> crate::CryptoKeystoreResult<Option<Self>> {
        get_helper_composite_key(
            conn,
            &[Self::PRIMARY_KEY_COLUMN_NAME],
            rusqlite::params![key.conversation_id],
            Self::from_row,
        )
    }

    fn count(conn: &rusqlite::Connection) -> crate::CryptoKeystoreResult<u32> {
        count_helper::<Self>(conn)
    }

    fn load_all(conn: &rusqlite::Connection) -> crate::CryptoKeystoreResult<Vec<Self>> {
        load_all_helper(conn, Self::from_row)
    }
}

impl EntityDatabaseMutation for TransientMessageTxCounter {
    type AutoGeneratedFields = ();

    fn save(&self, tx: &rusqlite::Transaction) -> crate::CryptoKeystoreResult<()> {
        let mut stmt = tx.prepare_cached(formatcp!(
            "INSERT OR REPLACE INTO {} (conversation_id, count) VALUES (?, ?)",
            TransientMessageTxCounter::TABLE_NAME
        ))?;
        stmt.execute(rusqlite::params![self.conversation_id, self.count])?;
        Ok(())
    }

    fn delete(
        tx: &rusqlite::Transaction,
        primary_key: &TransientMessageTxCounterPk,
    ) -> crate::CryptoKeystoreResult<bool> {
        delete_helper::<Self>(
            tx,
            Self::PRIMARY_KEY_COLUMN_NAME,
            primary_key.conversation_id.as_slice(),
        )
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, derive_more::Constructor)]
pub struct TransientMessageTxCounterPkRef<'a> {
    conversation_id: &'a [u8],
}

impl BorrowPrimaryKey for TransientMessageTxCounter {
    type BorrowedPrimaryKey<'a> = TransientMessageTxCounterPkRef<'a>;

    fn borrow_primary_key(&self) -> Self::BorrowedPrimaryKey<'_> {
        TransientMessageTxCounterPkRef::new(&self.conversation_id)
    }
}

impl From<TransientMessageTxCounterPkRef<'_>> for TransientMessageTxCounterPk {
    fn from(key: TransientMessageTxCounterPkRef<'_>) -> Self {
        Self::new(key.conversation_id.to_vec())
    }
}

impl EntityGetBorrowed for TransientMessageTxCounter {
    fn get_borrowed(
        conn: &rusqlite::Connection,
        key: Self::BorrowedPrimaryKey<'_>,
    ) -> crate::CryptoKeystoreResult<Option<Self>> {
        get_helper(conn, Self::PRIMARY_KEY_COLUMN_NAME, key.conversation_id, Self::from_row)
    }
}

impl EntityDeleteBorrowed for TransientMessageTxCounter {
    fn delete_borrowed(tx: &rusqlite::Transaction, id: Self::BorrowedPrimaryKey<'_>) -> CryptoKeystoreResult<bool> {
        delete_helper::<Self>(tx, Self::PRIMARY_KEY_COLUMN_NAME, id.conversation_id)
    }
}
