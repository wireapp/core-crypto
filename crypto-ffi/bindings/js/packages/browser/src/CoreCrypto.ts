export * from "../../../shared/src/CoreCrypto";

import { createSender } from "@ubjs/worker";
import core_crypto_ffi, {
    setLogger as setLoggerFfi,
    type CoreCryptoLogLevel,
} from "./autogenerated/core_crypto_ffi";
import {
    PLAYER_DEFINITIONS,
    setNativeModule,
} from "./autogenerated/core_crypto_ffi-ffi";
import type { WorkerStart, WorkerStarted } from "./worker";

let initPromise: Promise<void> | undefined;

/**
 * Initialises the wasm module necessary for running core crypto.
 *
 * CoreCrypto runs in a dedicated worker, which this starts from `worker.js` next to this file.
 *
 * @param path to the wasm module, e.g., on the local file system or a remote URL.
 *   If omitted, the module is loaded from `core_crypto_ffi.wasm` next to this file.
 */
export async function initWasmModule(path?: string | URL) {
    if (typeof Worker === "undefined") {
        throw Error(
            "`@wireapp/core-crypto` runs in a web worker, which this environment doesn't support. " +
                "Consider using the `@wireapp/core-crypto-native` package.",
        );
    }

    // Repeated calls share the first call's promise (only if it succeeded), so the module is only ever started once.
    initPromise ??= (async () => {
        const source =
            path ?? new URL("./core_crypto_ffi.wasm", import.meta.url);
        // Compiled here rather than in the worker, so that a relative `path` resolves against the page's URL.
        const module = await WebAssembly.compileStreaming(fetch(source));

        const worker = new Worker(new URL("./worker.js", import.meta.url), {
            type: "module",
        });

        // One channel for every call: the generated code relies on the order of its messages.
        const channel = new MessageChannel();
        try {
            await startWorker(worker, { module, port: channel.port2 });
            setNativeModule(createSender(PLAYER_DEFINITIONS, channel.port1));
            await core_crypto_ffi.initialize();
        } catch (e) {
            worker.terminate();
            throw e;
        }
    })();

    try {
        await initPromise;
    } catch (e) {
        initPromise = undefined;
        throw e;
    }
}

/** Hand the worker the module and its end of the channel, and wait until it serves calls. */
function startWorker(worker: Worker, start: WorkerStart): Promise<void> {
    return new Promise((resolve, reject) => {
        worker.addEventListener(
            "message",
            (event: MessageEvent<WorkerStarted>) => {
                if (event.data.ok) {
                    resolve();
                } else {
                    reject(
                        new Error(
                            `core-crypto's worker failed to start: ${event.data.error}`,
                        ),
                    );
                }
            },
            { once: true },
        );

        // Fires if the worker script fails to load or throws, so that this doesn't wait forever.
        worker.addEventListener(
            "error",
            (event) => {
                reject(
                    new Error(
                        `core-crypto's worker failed to start: ${event.message}`,
                    ),
                );
            },
            { once: true },
        );
        worker.postMessage(start, [start.port]);
    });
}

/** Forwards CoreCrypto's log messages to the platform's logging system. */
export interface CoreCryptoLogger {
    /**
     * CoreCrypto calls this method whenever it needs to log a message.
     *
     * CoreCrypto doesn't wait for this call, so an error thrown here is only reported to the console. A message can also
     * arrive after the CoreCrypto call that logged it has returned.
     */
    log(
        level: CoreCryptoLogLevel,
        message: string,
        context: string | undefined,
    ): void;
}

/** Initializes the logger. */
export async function setLogger(logger: CoreCryptoLogger): Promise<void> {
    await setLoggerFfi({
        log: async (level, message, context) =>
            logger.log(level, message, context),
    });
}
