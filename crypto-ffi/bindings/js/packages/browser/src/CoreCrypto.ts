export * from "../../../shared/src/CoreCrypto";

import { openWasm } from "@ubjs/wasm";
import core_crypto_ffi from "./autogenerated/core_crypto_ffi";
import {
    PLAYER_DEFINITIONS,
    setNativeModule,
} from "./autogenerated/core_crypto_ffi-ffi";
import { wasmImports } from "./autogenerated/wasm-imports";

let initPromise: Promise<void> | undefined;

/**
 * Initialises the wasm module necessary for running core crypto.
 *
 * @param path to the wasm module, e.g., on the local file system or a remote URL.
 *   If omitted, the module is loaded from `autogenerated/core_crypto_ffi.wasm` next to this file.
 */
export async function initWasmModule(path?: string) {
    if (typeof window === "undefined") {
        throw Error(
            "initializing the wasm module of `@wireapp/core-crypto` package outside the browser\
            isn't currently supported. Consider using the `@wireapp/core-crypto-native` package."
        );
    }
    // This does what `uniffiInitAsync` in the generated `index.ts` does, except that it also
    // resolves the wasm-bindgen snippets the module imports, which that one doesn't. Repeated
    // calls share the first call's promise, so the module is only ever opened once.
    initPromise ??= (async () => {
        const wasmModule = await openWasm(
            path ??
                new URL(
                    "./autogenerated/core_crypto_ffi.wasm",
                    import.meta.url
                ),
            { resolveModule: async (name) => wasmImports[name] }
        );
        setNativeModule(wasmModule.registerSync(PLAYER_DEFINITIONS));
        core_crypto_ffi.initialize();
    })();
    await initPromise;
}
