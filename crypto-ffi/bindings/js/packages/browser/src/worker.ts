// The dedicated worker CoreCrypto runs in. OPFS sync access handles, which the database needs, only exist in
// dedicated workers. `initWasmModule` starts this worker and talks to it through `@ubjs/worker`.

import { openWasm } from "@ubjs/wasm";
import { createReceiver, type RegisteredPlayer } from "@ubjs/worker";
import { PLAYER_DEFINITIONS } from "./autogenerated/core_crypto_ffi-ffi";
// Some of CoreCrypto's dependencies use wasm-bindgen, so the wasm imports the JS glue only wasm-bindgen can
// write. Importing it here keeps it in the bundle; the alternative is fetching it at runtime.
import * as wasmBindgenGlue from "./autogenerated/core_crypto_ffi_bg.js";

/** The message `initWasmModule` sends to start the worker. */
export interface WorkerStart {
    module: WebAssembly.Module;
    port: MessagePort;
}

/** The worker's answer to {@link WorkerStart}. */
export type WorkerStarted = { ok: true } | { ok: false; error: string };

/** Resolves the modules the wasm imports, for `openWasm`. */
async function resolveWasmBindgenGlue(
    name: string,
): Promise<Record<string, unknown>> {
    if (!name.endsWith("core_crypto_ffi_bg.js")) {
        throw new Error(
            `core-crypto's wasm imports "${name}", which only wasm-bindgen's glue should provide`,
        );
    }
    return wasmBindgenGlue as unknown as Record<string, unknown>;
}

self.addEventListener(
    "message",
    async (event: MessageEvent<WorkerStart>) => {
        const { module, port } = event.data;
        let reply: WorkerStarted;
        try {
            const wasm = await openWasm(module, {
                resolveModule: resolveWasmBindgenGlue,
            });
            // The same object: `@ubjs/wasm` and `@ubjs/worker` each declare their own type for it.
            const player = wasm.registerSync(
                PLAYER_DEFINITIONS,
            ) as unknown as RegisteredPlayer;
            createReceiver(PLAYER_DEFINITIONS, player, port);
            reply = { ok: true };
        } catch (e) {
            reply = { ok: false, error: String(e) };
        }
        self.postMessage(reply);
    },
    { once: true },
);
