use async_trait::async_trait;
use serde::{Deserialize, Serialize};

use crate::{
    CryptoKeystoreResult,
    connection::idb_migration::legacy::{
        connection::{KeystoreDatabaseConnection, TransactionWrapper},
        traits::{
            DecryptData, Decryptable, Decrypting, EncryptData, Encrypting, Entity, EntityBase, EntityDatabaseMutation,
            KeyType as _, UniqueEntity,
        },
    },
    traits::PrimaryKey,
};

/// The Proteus identity as the legacy IndexedDB schema stores it.
///
/// The live [`ProteusIdentity`][crate::entities::ProteusIdentity] has a unit primary key. The releases which wrote
/// IndexedDB keyed the identity by the single byte `[1]` on wasm, and that byte is both the object store key and
/// part of the additional authenticated data, so rows they wrote can only be read back with it exactly.
#[derive(core_crypto_macros::Debug)]
#[sensitive]
pub(crate) struct LegacyProteusIdentity {
    pub(crate) sk: Vec<u8>,
    pub(crate) pk: Vec<u8>,
}

impl LegacyProteusIdentity {
    /// Write this identity into the `proteus_identities` table, which has no key column.
    pub(crate) fn save(&self, tx: &rusqlite::Transaction<'_>) -> CryptoKeystoreResult<()> {
        let mut stmt = tx.prepare_cached("INSERT INTO proteus_identities (sk, pk) VALUES (?, ?)")?;
        stmt.execute((&self.sk, &self.pk))?;
        Ok(())
    }
}

impl PrimaryKey for LegacyProteusIdentity {
    type PrimaryKey = [u8; 1];

    fn primary_key(&self) -> Self::PrimaryKey {
        Self::KEY
    }
}

impl EntityBase for LegacyProteusIdentity {
    type ConnectionType = KeystoreDatabaseConnection;
    const TABLE_NAME: &'static str = "proteus_identities";
}

impl UniqueEntity for LegacyProteusIdentity {
    const KEY: [u8; 1] = [1];
}

#[async_trait(?Send)]
impl Entity for LegacyProteusIdentity {
    async fn get(conn: &mut Self::ConnectionType, _key: &Self::PrimaryKey) -> CryptoKeystoreResult<Option<Self>> {
        let identity = Self::load_all(conn).await?.pop();
        Ok(identity)
    }

    async fn count(conn: &mut Self::ConnectionType) -> CryptoKeystoreResult<u32> {
        conn.storage().count::<Self>().await
    }

    async fn load_all(conn: &mut Self::ConnectionType) -> CryptoKeystoreResult<Vec<Self>> {
        conn.storage().get_all().await
    }
}

#[async_trait(?Send)]
impl<'a> EntityDatabaseMutation<'a> for LegacyProteusIdentity {
    type Transaction = TransactionWrapper<'a>;
    type AutoGeneratedFields = ();

    async fn save(&'a self, tx: &Self::Transaction) -> CryptoKeystoreResult<()> {
        tx.save(self).await
    }

    async fn count(tx: &Self::Transaction) -> CryptoKeystoreResult<u32> {
        tx.count::<Self>().await
    }

    async fn delete(tx: &Self::Transaction, id: &Self::PrimaryKey) -> CryptoKeystoreResult<bool> {
        tx.delete::<Self>(id.bytes().as_ref()).await
    }
}

#[derive(Serialize, Deserialize)]
pub(crate) struct ProteusIdentityEncrypted<'a> {
    #[serde(skip)]
    _lifetime: std::marker::PhantomData<&'a ()>,
    sk: Vec<u8>,
    pk: Vec<u8>,
}

impl<'a> Encrypting<'a> for LegacyProteusIdentity {
    type EncryptedForm = ProteusIdentityEncrypted<'a>;

    fn encrypt(&self, cipher: &aes_gcm::Aes256Gcm) -> CryptoKeystoreResult<Self::EncryptedForm> {
        let sk = <Self as EncryptData>::encrypt_data(self, cipher, &self.sk)?;
        let pk = <Self as EncryptData>::encrypt_data(self, cipher, &self.pk)?;
        Ok(ProteusIdentityEncrypted {
            _lifetime: std::marker::PhantomData,
            sk,
            pk,
        })
    }
}

impl Decrypting<'static> for ProteusIdentityEncrypted<'static> {
    type DecryptedForm = LegacyProteusIdentity;

    fn decrypt(self, cipher: &aes_gcm::Aes256Gcm) -> CryptoKeystoreResult<Self::DecryptedForm> {
        let sk = <LegacyProteusIdentity as DecryptData>::decrypt_data(cipher, &LegacyProteusIdentity::KEY, &self.sk)?;
        let pk = <LegacyProteusIdentity as DecryptData>::decrypt_data(cipher, &LegacyProteusIdentity::KEY, &self.pk)?;
        Ok(LegacyProteusIdentity { sk, pk })
    }
}

impl Decryptable<'static> for LegacyProteusIdentity {
    type DecryptableFrom = ProteusIdentityEncrypted<'static>;
}
