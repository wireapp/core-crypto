//! When a client joins a group via an external commit, it sometimes receives messages
//! for the new epoch whereas it does not yet have
//! the confirmation from the DS that the external join commit has been accepted.

use core_crypto_keystore::{entities::PersistedMlsGroup, traits::EntityDatabaseMutation as _};
use openmls::prelude::MlsGroup;

use super::{Result, group_metadata};
use crate::{
    CommitBundle, ConversationConfiguration, KeystoreError, OpenMlsError, RecursiveError,
    mls::conversation::ConversationIdRef, mls_provider::CryptoProvider, transaction_context::TransactionContext,
};

/// A pending conversation is a conversation that has been created via an external join commit
/// locally, while this commit has not yet been approved by the DS.
#[derive(Debug)]
pub(crate) struct PendingConversation {
    inner: PersistedMlsGroup,
    context: TransactionContext,
}

impl PendingConversation {
    pub(crate) fn new(inner: PersistedMlsGroup, context: TransactionContext) -> Self {
        Self { inner, context }
    }

    pub(crate) async fn from_mls_group(group: MlsGroup, context: TransactionContext) -> Result<Self> {
        let serialized_group =
            core_crypto_keystore::ser(&group).map_err(KeystoreError::wrap("serializing mls group"))?;
        let group_id = group.group_id().as_slice();
        let database = context
            .database()
            .map_err(RecursiveError::context("getting database from transaction context"))?;

        // A group we have just built by external commit is active, as required by
        // `current_credential`: our leaf is staged in the pending commit, not yet in the tree.
        let current_credential = group_metadata::current_credential_pk(&group, &*database).await?;
        let inner = PersistedMlsGroup {
            id: group_id.into(),
            state: serialized_group,
            epoch: group.epoch().as_u64(),
            ciphersuite: group.ciphersuite() as u16,
            credential_id: current_credential.public_key_hash,
            credential_type: current_credential.credential_type,
            credential_not_before: current_credential.not_before,
            own_leaf_index: group.own_leaf_index().u32(),
            is_pending: true,
            tnt_tx_counter: Default::default(),
        };
        Ok(Self::new(inner, context))
    }

    async fn mls_provider(&self) -> Result<CryptoProvider> {
        self.context
            .crypto_provider()
            .await
            .map_err(RecursiveError::context("getting mls provider"))
            .map_err(Into::into)
    }

    fn id(&self) -> &ConversationIdRef {
        ConversationIdRef::new(self.inner.id.bytes())
    }

    pub(crate) async fn save(&self) -> Result<()> {
        let context = self
            .context
            .inner()
            .map_err(RecursiveError::context("getting inner context"))?;
        let tx = context.transaction();
        self.inner
            .save(tx)
            .map_err(KeystoreError::wrap("saving mls pending groups"))?;
        // When saving, we may be overwriting an existing non-pending mls group.
        // In that case, we have to clear it from the conversation cache to ensure
        // that the proper state is loaded on next use.
        self.context
            .mls_groups()
            .await
            .map_err(RecursiveError::context(
                "getting conversation cache when saving pending conversation",
            ))?
            .remove(self.id());
        Ok(())
    }

    /// Send the commit via [crate::MlsTransport] and handle the response.
    pub(crate) async fn send_commit(&self, commit: CommitBundle) -> Result<()> {
        let transport = self
            .context
            .mls_transport()
            .await
            .map_err(RecursiveError::context("getting mls transport"))?;

        transport
            .send_commit_bundle(commit)
            .await
            .map_err(RecursiveError::context("sending commit bundle"))
            .map_err(Into::into)
    }

    /// This merges the commit generated by [TransactionContext::join_by_external_commit],
    /// persists the group permanently and deletes the temporary one. After merging, the group
    /// is fully functional.
    ///
    /// # Errors
    /// Errors resulting from OpenMls, the KeyStore calls and deserialization
    pub(crate) async fn merge(&mut self) -> Result<()> {
        let mls_provider = self.mls_provider().await?;
        let group = &self.inner.state;

        let mut mls_group =
            core_crypto_keystore::deser::<MlsGroup>(group).map_err(KeystoreError::wrap("deserializing mls group"))?;

        // Merge it aka bring the MLS group to life and make it usable
        mls_group
            .merge_pending_commit(&mls_provider)
            .await
            .map_err(OpenMlsError::wrap("merging pending commit"))?;

        // Restore the configuration
        let configuration = ConversationConfiguration {
            cipher_suite: mls_group.ciphersuite().into(),
            ..Default::default()
        };

        // Persist the now usable MLS group in the keystore
        // This is the now merged conversation
        let context = &self.context;
        context
            .persist_conversation_from_mls_group(mls_group, configuration)
            .await
            .map_err(RecursiveError::context(
                "persisting a pending conversation from mls group",
            ))?;

        // cleanup the pending group we no longer need
        self.clear().await?;

        Ok(())
    }

    /// In case the external commit generated by [TransactionContext::join_by_external_commit] is
    /// rejected by the Delivery Service, and we want to abort this external commit,
    /// we can wipe out the pending group from the keystore.
    ///
    /// # Errors
    /// Errors resulting from the KeyStore calls
    pub(crate) async fn clear(&mut self) -> Result<()> {
        let context = self
            .context
            .inner()
            .map_err(RecursiveError::context("getting inner context"))?;
        let tx = context.transaction();
        let group_id = self.id();
        PersistedMlsGroup::delete_if_pending(tx, group_id.keystore())
            .map_err(KeystoreError::wrap("deleting pending group by id"))?;
        // We may have stored this pending conversation in the conversation cache.
        // In that case, we have to clear it.
        self.context
            .mls_groups()
            .await
            .map_err(RecursiveError::context(
                "getting conversation cache when saving pending conversation",
            ))?
            .remove(self.id());
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use crate::test_utils::*;

    /// Abandoning an external join abandons the messages buffered while it was pending.
    ///
    /// [`PendingConversation::clear`] deletes the pending group and cascades to several dependent tables.
    /// Ensure those deletions propagate.
    #[apply(all_cred_cipher)]
    async fn abandoning_an_external_join_abandons_buffered_messages(case: TestContext) {
        let [alice, mut bob] = case.sessions().await;
        Box::pin(async move {
            let conversation = case.create_conversation([&alice]).await;

            // Bob asks to join Alice's group with an external commit, and waits for the DS to accept it.
            let (commit_guard, mut pending_conversation) = conversation.external_join_unmerged(&bob).await;
            let conversation = commit_guard.finish();

            // While Bob waits, Alice speaks. Bob can process nothing until his own join is merged, so he
            // buffers her message to replay afterwards.
            let app_msg = conversation
                .guard()
                .await
                .encrypt_message(b"Hello Bob !")
                .await
                .unwrap();
            assert!(
                matches!(
                    bob.transaction.conversation(conversation.id()).await.unwrap_err(),
                    crate::transaction_context::Error::PendingConversation(_)
                ),
                "Bob should not have the conversation yet"
            );
            let decrypted = bob
                .transaction
                .conversation_regardless_of_pending_status(conversation.id())
                .await
                .unwrap()
                .decrypt_message(app_msg)
                .await
                .unwrap();
            assert!(decrypted.is_empty(), "Alice's message must have been deferred");

            let counts = bob.transaction.count_entities().await;
            assert_eq!(counts.pending_group, 1, "Bob's join is still pending");
            assert_eq!(counts.pending_messages, 1, "Alice's message must have been buffered");

            // The DS rejects Bob's commit, so he gives up on the join.
            pending_conversation.clear().await.unwrap();

            drop(conversation);
            bob.commit_transaction().await;

            let counts = bob.transaction.count_entities().await;
            assert_eq!(
                counts.pending_group, 0,
                "abandoning the join must have removed the pending group"
            );
            assert_eq!(
                counts.pending_messages, 0,
                "the buffered message belongs to a pending conversation which was abandoned, so abandoning \
                 it must have taken the message with it"
            );
        })
        .await
    }

    #[apply(all_cred_cipher)]
    async fn should_buffer_and_reapply_messages_after_external_commit_merged(case: TestContext) {
        let [alice, bob, charlie, debbie] = case.sessions().await;
        Box::pin(async move {
            let conversation = case.create_conversation([&alice, &debbie]).await;
            // Bob tries to join Alice's group with an external commit
            let (commit_guard, _pending_conversation) = conversation.external_join_unmerged(&bob).await;
            let external_commit = commit_guard.message();

            // Alice decrypts the external commit...
            let conversation = commit_guard
                .notify_member(&alice)
                .await
                .process_member_changes()
                .await
                .finish();

            // ...then Alice generates new messages for this epoch
            let app_msg = conversation
                .guard()
                .await
                .encrypt_message(b"Hello Bob !")
                .await
                .unwrap();

            // And proposes to remove debbie
            let proposal_guard = conversation.remove_proposal(&debbie).await;
            let remove_proposal = proposal_guard.message();

            let conversation = proposal_guard.finish();

            let commit_guard = conversation.invite([&charlie]).await;
            let commit = commit_guard.message();
            let conversation = commit_guard.process_member_changes().await.finish();

            // And now Bob will have to decrypt those messages while he hasn't yet merged its external commit
            // To add more fun, he will buffer the messages in exactly the wrong order (to make
            // sure he reapplies them in the right order afterwards)
            assert!(
                matches!(
                    bob.transaction.conversation(conversation.id()).await.unwrap_err(),
                    crate::transaction_context::Error::PendingConversation(_)
                ),
                "Bob should not have the conversation yet"
            );
            let mut bob_conversation = bob
                .transaction
                .conversation_regardless_of_pending_status(conversation.id())
                .await
                .unwrap();
            let messages = [remove_proposal, commit].map(|m| m.to_bytes().unwrap());
            for message in messages.into_iter().chain([app_msg]) {
                let decrypted = bob_conversation.decrypt_message(message).await.unwrap();
                assert!(decrypted.is_empty(), "the message must have been deferred");
            }

            // Bob should have buffered the messages
            assert_eq!(bob.transaction.count_entities().await.pending_messages, 3);

            let observer = TestEpochObserver::new();
            bob.session()
                .await
                .register_epoch_observer(observer.clone())
                .await
                .unwrap();

            // Finally, Bob receives the green light from the DS and he can merge the external commit
            let mut decrypted = bob_conversation
                .decrypt_message(external_commit.to_bytes().unwrap())
                .await
                .unwrap()
                .into_iter();
            assert!(
                decrypted.next().unwrap().is_commit(),
                "the first message must be Bob's own join commit"
            );
            assert!(
                !bob_conversation.group().await.is_pending,
                "merging the join commit must have made the conversation established"
            );

            let restored = decrypted.collect::<Vec<_>>();
            assert_eq!(restored.len(), 3, "all buffered messages must have been restored");
            let plaintexts = restored
                .iter()
                .filter_map(|message| message.as_application_message())
                .map(|message| message.plaintext.as_slice())
                .collect::<Vec<_>>();
            assert_eq!(plaintexts, [b"Hello Bob !".as_slice()]);
            assert_eq!(restored.iter().filter(|message| message.is_proposal()).count(), 1);
            assert_eq!(restored.iter().filter(|message| message.is_commit()).count(), 1);

            assert_eq!(conversation.member_count().await, 3);
            assert!(conversation.is_functional().await);
            assert!(conversation.is_functional_and_contains([&alice, &bob, &charlie]).await);

            // After merging we should erase all those pending messages
            assert_eq!(bob.transaction.count_entities().await.pending_messages, 0);

            let final_epoch = bob_conversation.epoch().await;
            drop(bob_conversation);
            bob.transaction.finish().await.unwrap();

            // Bob's conversation advanced twice: once when his join commit was merged,
            // and once more when Alice's commit adding Charlie was restored.
            let observed_epochs = observer.observed_epochs().await;
            let expected_epochs = [final_epoch - 1, final_epoch].map(|epoch| (conversation.id().clone(), epoch));
            assert_eq!(observed_epochs, expected_epochs);
        })
        .await
    }

    #[apply(all_cred_cipher)]
    async fn should_not_reapply_buffered_messages_when_rejoining(case: TestContext) {
        let [alice, bob] = case.sessions().await;
        Box::pin(async move {
            let conversation = case.create_conversation([&alice, &bob]).await;

            // Alice will never see this commit
            let conversation = conversation.acting_as(&bob).await;
            let commit_guard = conversation.update().await;
            let conversation = commit_guard.conversation();

            let msg1 = conversation.guard().await.encrypt_message("A").await.unwrap();
            let msg2 = conversation.guard().await.encrypt_message("B").await.unwrap();

            let conversation = commit_guard.finish();
            // Since Alice missed Bob's commit she should buffer this message
            let decrypt = conversation.guard().await.decrypt_message(msg1).await;
            assert!(decrypt.unwrap().is_empty(), "the message must have been deferred");
            let decrypt = conversation.guard().await.decrypt_message(msg2).await;
            assert!(decrypt.unwrap().is_empty(), "the message must have been deferred");
            assert_eq!(alice.transaction.count_entities().await.pending_messages, 2);

            let conversation = conversation.acting_as(&bob).await.external_join_notify(&alice).await;
            // Alice should have deleted all her buffered messages
            assert_eq!(alice.transaction.count_entities().await.pending_messages, 0);
            assert!(conversation.is_functional_and_contains([&alice, &bob]).await);
        })
        .await
    }
}
