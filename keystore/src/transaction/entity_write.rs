//! These methods alow mutating the transaction. Mutations will be propagated to the database on commit.

use super::dynamic_dispatch::EntityId;
use crate::{
    CryptoKeystoreError, CryptoKeystoreResult,
    traits::{BorrowPrimaryKey, DeletableBySearchKey, EntityDatabaseMutation, EntityDeleteBorrowed, KeyType},
    transaction::{Operation, Transaction},
};

impl Transaction {
    /// Save an entity into this transaction.
    ///
    /// This is a multi-step process:
    ///
    /// - Adjust the entity by calling its [`pre_save()`][EntityDatabaseMutation::pre_save] method.
    /// - Store the entity in an internal map.
    ///   - Remove the entity from the set of deleted entities, if it was there.
    /// - On [`commit`][crate::UniqueArc::<Self>::commit], actually persist the entity into the supplied database.
    pub async fn save<E>(&self, mut entity: E) -> CryptoKeystoreResult<E::AutoGeneratedFields>
    where
        E: 'static + EntityDatabaseMutation + Send + Sync,
    {
        let auto_generated_fields = entity.pre_save()?;

        {
            let mut operations = self.operations.write().await;
            operations.push(Operation::upsert(entity));
        }

        Ok(auto_generated_fields)
    }

    async fn remove_by_entity_id<E>(&self, entity_id: EntityId) -> CryptoKeystoreResult<()>
    where
        E: EntityDatabaseMutation,
    {
        let mut operations = self.operations.write().await;
        operations.push(Operation::delete::<E>(entity_id));
        Ok(())
    }

    /// Remove an entity by its primary key.
    ///
    /// Where the primary key has a distinct borrowed form, consider [`Self::remove_borrowed`].
    ///
    /// Note that this doesn't return whether or not anything was actually removed because
    /// that won't happen until the transaction is committed.
    pub async fn remove<E>(&self, id: &E::PrimaryKey) -> CryptoKeystoreResult<()>
    where
        E: EntityDatabaseMutation,
    {
        let entity_id = EntityId::from_primary_key::<E>(id).ok_or(CryptoKeystoreError::UnknownTable(E::TABLE_NAME))?;
        self.remove_by_entity_id::<E>(entity_id).await
    }

    /// Remove an entity by the borrowed form of its primary key.
    ///
    /// Note that this doesn't return whether or not anything was actually removed because
    /// that won't happen until the transaction is committed.
    pub async fn remove_borrowed<E>(&self, id: &E::BorrowedPrimaryKey) -> CryptoKeystoreResult<()>
    where
        E: EntityDeleteBorrowed + BorrowPrimaryKey,
    {
        let entity_id =
            EntityId::from_borrowed_primary_key::<E>(id).ok_or(CryptoKeystoreError::UnknownTable(E::TABLE_NAME))?;
        self.remove_by_entity_id::<E>(entity_id).await
    }

    /// Restore an entity that was deleted in this transaction by removing its delete operations.
    /// This is idempotent: if the entity was never deleted, this changes nothing.
    ///
    /// NOTE: This will only work if the entity has been added in an earlier transaction, because otherwise,
    /// removing its id from the deleted list wouldn't suffice: we'd need to replay its insertion.
    ///
    /// CAUTION: Does not affect entities which were bulk-deleted.
    ///
    /// CAUTION: Entities which are restored might still be overwritten within this transaction.
    pub async fn restore<E>(&self, id: &E::BorrowedPrimaryKey) -> CryptoKeystoreResult<()>
    where
        E: EntityDeleteBorrowed + BorrowPrimaryKey,
    {
        let entity_id =
            EntityId::from_borrowed_primary_key::<E>(id).ok_or(CryptoKeystoreError::UnknownTable(E::TABLE_NAME))?;

        {
            let mut operations = self.operations.write().await;
            for operation in operations.iter_mut() {
                if operation
                    .as_delete::<E>()
                    .is_some_and(|operation_entity_id| entity_id == operation_entity_id)
                {
                    *operation = Operation::Nop;
                }
            }
        }

        Ok(())
    }

    /// Bulk-remove entities matching a given search key.
    pub async fn bulk_remove<E, S>(&self, search_key: S)
    where
        E: 'static + DeletableBySearchKey<S>,
        S: 'static + KeyType,
    {
        let mut operations = self.operations.write().await;
        operations.push(Operation::bulk_delete::<E, S>(search_key))
    }
}
