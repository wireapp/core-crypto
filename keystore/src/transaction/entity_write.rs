//! These methods alow mutating the transaction. Mutations will be propagated to the database on commit.

use super::dynamic_dispatch::EntityId;
use crate::{
    CryptoKeystoreError, CryptoKeystoreResult,
    traits::{BorrowPrimaryKey, Entity, EntityDatabaseMutation, EntityDeleteBorrowed},
    transaction::Transaction,
};

impl Transaction {
    /// Save an entity into this transaction.
    ///
    /// This is a multi-step process:
    ///
    /// - Adjust the entity by calling its [`pre_save()`][Entity::pre_save] method.
    /// - Store the entity in an internal map.
    ///   - Remove the entity from the set of deleted entities, if it was there.
    /// - On [`Self::commit`], actually persist the entity into the supplied database.
    pub async fn save<E>(&self, mut entity: E) -> CryptoKeystoreResult<E::AutoGeneratedFields>
    where
        E: Entity + EntityDatabaseMutation + Send + Sync,
    {
        let auto_generated_fields = entity.pre_save()?;

        let entity_id =
            EntityId::from_entity(&entity).ok_or(CryptoKeystoreError::UnknownCollectionName(E::COLLECTION_NAME))?;
        {
            let mut cache_guard = self.cache.write().await;
            // We need to ensure that we always move the entity to the end of the insertion order, so that
            // we don't accidentally overwrite an old entity in the transaction and end up playing it back
            // in the real transaction too early, in a way that would violate a constraint.
            let cache_len = cache_guard.len();
            cache_guard.insert_before(cache_len, entity_id.clone(), entity.into());
        }
        {
            // at this point remove the entity from the set of deleted entities to ensure that
            // this new data gets propagated
            let mut cache_guard = self.deleted.write().await;
            cache_guard.remove(&entity_id);
        }

        Ok(auto_generated_fields)
    }

    async fn remove_by_entity_id(&self, entity_id: EntityId) -> CryptoKeystoreResult<()> {
        // rm this entity from the set of added/modified items
        // it might never touch the real db at all
        let mut cache_guard = self.cache.write().await;
        cache_guard.remove(&entity_id);

        // add this entity to the set of items which should be deleted from the persisted db
        let mut deleted_set = self.deleted.write().await;
        deleted_set.insert(entity_id);
        Ok(())
    }

    /// Remove an entity by its primary key.
    ///
    /// Where the primary key has a distinct borrowed form, consider [`Self::remove_borrowed`].
    ///
    /// Note that this doesn't return whether or not anything was actually removed because
    /// that won't happen until the transaction is committed.
    pub async fn remove<E>(&self, id: &E::PrimaryKey) -> CryptoKeystoreResult<()>
    where
        E: Entity + EntityDatabaseMutation,
    {
        let entity_id = EntityId::from_primary_key::<E>(id)
            .ok_or(CryptoKeystoreError::UnknownCollectionName(E::COLLECTION_NAME))?;
        self.remove_by_entity_id(entity_id).await
    }

    /// Remove an entity by the borrowed form of its primary key.
    ///
    /// Note that this doesn't return whether or not anything was actually removed because
    /// that won't happen until the transaction is committed.
    pub async fn remove_borrowed<E>(&self, id: &E::BorrowedPrimaryKey) -> CryptoKeystoreResult<()>
    where
        E: EntityDeleteBorrowed + BorrowPrimaryKey,
    {
        let entity_id = EntityId::from_borrowed_primary_key::<E>(id)
            .ok_or(CryptoKeystoreError::UnknownCollectionName(E::COLLECTION_NAME))?;
        self.remove_by_entity_id(entity_id).await
    }

    /// Restore an entity that was deleted in this transaction by removing it from the deleted list. This is
    /// idempotent: if the entity doesn't exist in the deleted list, do nothing.
    ///
    /// NOTE: This will only work if the entity has been added in an earlier transaction, because otherwise,
    /// removing its id from the deleted list wouldn't suffice: we'd need to replay its insertion.
    pub async fn restore<E>(&self, id: &E::BorrowedPrimaryKey) -> CryptoKeystoreResult<()>
    where
        E: EntityDeleteBorrowed + BorrowPrimaryKey,
    {
        let entity_id = EntityId::from_borrowed_primary_key::<E>(id)
            .ok_or(CryptoKeystoreError::UnknownCollectionName(E::COLLECTION_NAME))?;
        let mut deleted = self.deleted.write().await;
        deleted.remove(&entity_id);
        Ok(())
    }
}
